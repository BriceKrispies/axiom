#!/usr/bin/env node
/**
 * BAKE THE SURFACE TEXTURES AT BUILD TIME.
 *
 * WHY. The nineteen procedural surface shaders are the largest single block of
 * work in a cold boot — ~14 s of serial GPU shader compilation for programs
 * that each run four full-screen draws and are then discarded. Measured by
 * skipping them outright (`?bakes=skip`), removing them is worth ~14 s off
 * "settled" and ~17 s off the weapon reaching the player's hands. Nothing else
 * available is close.
 *
 * The textures are a pure function of (glsl, seed, params, size), so they only
 * ever needed to be computed once. This computes them once.
 *
 * HOW. It drives the app's OWN forge, on a real GPU, in a real browser, and
 * reads the render targets back — see src/dev/bakedump.js. A CPU
 * reimplementation would be a second source of truth that could drift from the
 * shader silently; running the shader is the only way the asset cannot be wrong
 * in a way nobody notices.
 *
 * WHAT IT IS WORTH. Cold — the only regime that gates, see CLAUDE.md — these
 * are NEUTRAL: settled 34.9 s baked against 34.8 s procedural, medians of
 * three. Warm they take `loaded` down by ~14 s, which is the regime a
 * returning player lives in, and that is the whole reason they exist. Do not
 * quote the 14 s as a boot improvement.
 *
 * That figure took three attempts to establish. It read neutral, then as a
 * 24.5 s win, then neutral again — the middle reading was against a procedural
 * path that had a 27 s regression in it at the time. Cold is necessary and not
 * sufficient: hold everything else still, or a cold number misleads exactly as
 * well as a warm one.
 *
 * FORMAT. LOSSLESS WebP at a reduced resolution, encoded by the browser itself
 * so this needs no build dependency. Measured over the full set:
 *
 *     PNG, 1K                96.3 MB
 *     WebP lossless, 1K      69.4 MB
 *     WebP q0.92, 1K         17.6 MB   <- renders WRONG, see below
 *     WebP lossless, --q=low 21.9 MB   <- shipped
 *
 * Lossy is not available here, however tempting the size is. The ORM map packs
 * ambient occlusion, roughness and metalness into R, G and B as three
 * INDEPENDENT data channels, and WebP's lossy mode subsamples chroma — which
 * mixes them. The result is a level rendered as though every surface were
 * polished metal. It was tried, it looked exactly that wrong, and the fix is
 * resolution rather than quantisation: a smaller lossless bake degrades
 * uniformly and predictably, and the runtime upscales it into whatever target
 * it allocated.
 *
 * USAGE
 *   uv run scripts/localhost_servers.py start-app shmup --port 4173   # or any server
 *   node tools/bake-textures.mjs --quality=1 --q=low [--port=4173] [--out=public/baked]
 *
 * The output is gitignored: 22 MB of generated bytes belong in a build step,
 * not in the repo. A checkout without them falls back to the procedural forge,
 * which is still the source of truth — so if the warm benefit is wanted in a
 * deployed build, the deploy has to run this.
 *
 * The output is content-addressed by the surface's cache key, so a library edit
 * changes the filename and a stale asset cannot be served in place of a fresh
 * one. `--check` re-bakes and reports drift without writing.
 */
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync, rmSync, existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, '').split('=');
    return [k, v ?? true];
  })
);

const PORT = Number(args.port ?? 4173);
const QUALITY = Number(args.quality ?? 0.92);
const OUT = resolve(String(args.out ?? 'public/baked'));
const TIMEOUT = Number(args.timeout ?? 300000);
const CHECK = !!args.check;

/** Stable, filesystem-safe name for a surface's cache key. */
const nameFor = (key, channel) =>
  `${createHash('sha1').update(key).digest('hex').slice(0, 16)}-${channel}.webp`;

const ANGLE = { win32: 'd3d11', darwin: 'metal' }[process.platform] ?? 'gl';

const ctx = await chromium.launchPersistentContext(
  join(process.env.TEMP ?? '/tmp', 'shmup-bake-profile'),
  {
    headless: !args.headed,
    viewport: { width: 640, height: 360 },
    args: [
      '--ignore-gpu-blocklist',
      '--mute-audio',
      '--enable-gpu-rasterization',
      '--disable-background-timer-throttling',
      // The bake must run on a real GPU. A SwiftShader fallback would produce
      // textures that are subtly not what the game draws, and nothing
      // downstream would be able to tell.
      `--use-angle=${ANGLE}`,
    ],
  }
);

const page = await ctx.newPage();
page.on('pageerror', (e) => console.error('[page]', e.message ?? e));

// `q=ultra` so the textures come out at full resolution: the runtime downscales
// for lower presets, but it cannot invent detail a smaller bake never had.
// `bakes=issued` keeps the normal boot path, so the sets that get baked are
// exactly the sets the game asks for.
// The preset decides the texture budget, and therefore the asset size. `ultra`
// is 1K and bakes lossless to ~69 MB, which is not a shippable download;
// `medium` is 512 and quarters it. The runtime blits whatever it is given into
// the target it allocated, so a smaller bake simply upscales — a predictable,
// uniform softening, as opposed to the lossy-compression alternative, which
// destroys the ORM map outright because its three channels are independent DATA
// and WebP subsamples chroma.
const url = `http://127.0.0.1:${PORT}/?bakedump=1&q=${args.q ?? 'ultra'}`;
process.stderr.write(`baking from ${url} ...\n`);
await page.goto(url, { waitUntil: 'commit', timeout: TIMEOUT });
await page.waitForFunction('window.__LOADED__ === true', null, { timeout: TIMEOUT });

const result = await page.evaluate(
  (quality) => window.__DUMPBAKES__({ type: 'image/webp', quality }),
  QUALITY
);
await ctx.close();

if (!result?.ok) {
  console.error('bake failed:', result?.reason ?? 'no result');
  process.exit(4);
}

const manifest = { quality: QUALITY, sets: {} };
let total = 0;
const written = [];

for (const entry of result.sets) {
  const files = {};
  for (const [channel, map] of Object.entries(entry.maps)) {
    const bytes = Buffer.from(map.b64, 'base64');
    const file = nameFor(entry.key, channel);
    files[channel] = file;
    total += bytes.length;
    written.push({ file, bytes });
  }
  manifest.sets[entry.key] = {
    size: entry.size,
    worldSize: entry.worldSize,
    relief: entry.relief,
    files,
  };
}

const manifestText = JSON.stringify(manifest, null, 2);

if (CHECK) {
  const previous = existsSync(join(OUT, 'manifest.json'))
    ? readFileSync(join(OUT, 'manifest.json'), 'utf8')
    : '';
  const drifted = previous !== manifestText;
  console.log(
    drifted
      ? 'DRIFT: the baked textures do not match the current library. Re-run without --check.'
      : `up to date — ${result.sets.length} sets, ${(total / 1048576).toFixed(1)} MB`
  );
  process.exit(drifted ? 1 : 0);
}

// Rewritten wholesale rather than merged: a stale file from a surface that no
// longer exists is dead weight that nothing would ever notice.
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const { file, bytes } of written) writeFileSync(join(OUT, file), bytes);
writeFileSync(join(OUT, 'manifest.json'), manifestText);

console.log(
  `baked ${result.sets.length} surfaces · ${written.length} maps · ` +
    `${(total / 1048576).toFixed(1)} MB at q${QUALITY} -> ${OUT}`
);
